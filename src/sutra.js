// 섹션 ID로 빠른 조회
export const sectionById = Object.fromEntries(
  sections.map((s) => [s.id, s]),
);

// 긴 글 모드 — 전체 섹션 합친 줄 목록 (섹션 경계는 별도 메타로)
export function getAllLines() {
  const result = [];
  sections.forEach((s) => {
    s.lines.forEach((line, idx) => {
      result.push({ sectionId: s.id, lineIndex: idx, text: line });
    });
  });
  return result;
}

// 한 섹션의 총 글자 수 (공백 포함)
export function sectionCharCount(section) {
  return section.lines.reduce((acc, l) => acc + l.length, 0);
}
